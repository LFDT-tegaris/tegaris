#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct OperationDescriptor {
    pub id: &'static str,
    pub name: &'static str,
    pub request_type: &'static str,
    pub response_type: &'static str,
    pub state_machine: &'static str,
    pub allowed_from_states: &'static [&'static str],
    pub success_states: &'static [&'static str],
    pub action_intent_id: &'static str,
    pub webauthn_step_up_required: bool,
    pub maker_checker_required: bool,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ErrorDescriptor {
    pub id: &'static str,
    pub http_status: u16,
    pub name: &'static str,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct EventDescriptor {
    pub id: &'static str,
    pub event_type: &'static str,
}

