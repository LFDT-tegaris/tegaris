import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { definitionDigest } from '../src/business-transition/definition.ts';

/** Exact additional canonical families, registered by the existing generator. */
export async function registerEvidenceArchiveProfiles(registry, root, emit) {
  const admitted = [
    ['evidence-sink-profile-v1', 24002, 339, 'EvidenceSinkProfileV1'],
    ['evidence-sink-receipt-v1', 24003, 340, 'EvidenceSinkReceiptV1'],
    ['evidence-protected-sink-profile-v1', 24004, 341, 'EvidenceProtectedSinkProfileV1'],
    ['evidence-protected-sink-receipt-v1', 24005, 342, 'EvidenceProtectedSinkReceiptV1'],
  ];
  const contexts = {};
  for (const [file, schemaId, purposeCode, typeName] of admitted) {
    const projection = `schemas/canonical/${file}.json`;
    const definition = JSON.parse(await readFile(new URL(projection, root), 'utf8'));
    if (
      definition.schemaId !== schemaId ||
      definition.purpose.code !== purposeCode ||
      definition.schemaVersion !== 1 ||
      definition.semanticVersion !== '1.0.0' ||
      definition.typeName !== typeName
    )
      throw new Error('Archive schema allocation mismatch');
    const digest = `sha256:${definitionDigest(definition).toString('hex')}`;
    const entry = {
      ownerLane: 'LANE-CONTROL',
      projectionRefs: [projection],
      purpose: definition.purpose.name,
      purposeCode,
      schemaDigest: digest,
      schemaId,
      schemaVersion: '1.0.0',
      signatureContextRule:
        'PC_COSE_SIGN1_PROFILE_2_ES256_EXACT_TAGGED_PAYLOAD_DEFINITION_AAD_AND_HOST_ADMITTED_ARCHIVE_KEY',
      signed: true,
      typeName,
    };
    for (const item of registry.entries) {
      if (
        item.schemaId === schemaId ||
        item.purpose === entry.purpose ||
        item.purposeCode === purposeCode ||
        item.typeName === typeName
      ) {
        if (
          item.schemaId !== schemaId ||
          item.purpose !== entry.purpose ||
          item.purposeCode !== purposeCode ||
          item.typeName !== typeName ||
          item.schemaVersion !== '1.0.0' ||
          item.schemaDigest !== digest
        )
          throw new Error('Archive allocation collision or frozen definition drift');
      }
    }
    const index = registry.entries.findIndex((value) => value.schemaId === schemaId);
    if (index < 0) registry.entries.push(entry);
    else registry.entries[index] = entry;
    contexts[typeName] = {
      schemaId,
      schemaVersion: 1,
      purposeCode,
      purpose: entry.purpose,
      definitionDigest: digest,
      contentType: definition.cose.contentType,
      externalAadHex: definition.cose.externalAadHex,
      signatureProfileVersion: definition.cose.signatureProfileVersion,
      fields: definition.fields,
    };
  }
  const path = new URL('../src/evidence-archive/generated.ts', import.meta.url);
  const source = `// Generated by the canonical receipt/profile generator. Do not edit.\nexport const evidenceArchiveProfiles = ${JSON.stringify(contexts, null, 2)} as const;\n`;
  await emit(
    path,
    await format(source, { ...(await resolveConfig(fileURLToPath(path))), parser: 'typescript' }),
  );
}
