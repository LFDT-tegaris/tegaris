import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { definitionDigest } from '../src/business-transition/definition.ts';

export async function registerEvidenceExportProfile(registry, root, emit) {
  const projection = 'schemas/canonical/evidence-export-completion-receipt-v1.json';
  const definition = JSON.parse(await readFile(new URL(projection, root), 'utf8'));
  if (
    definition.schemaId !== 24013 ||
    definition.purpose.code !== 350 ||
    definition.schemaVersion !== 1 ||
    definition.semanticVersion !== '1.0.0' ||
    definition.typeName !== 'EvidenceExportCompletionReceiptV1' ||
    definition.ownerLane !== 'LANE-CONTROL'
  )
    throw new Error('Evidence export schema allocation mismatch');
  const schemaDigest = `sha256:${definitionDigest(definition).toString('hex')}`;
  const entry = {
    ownerLane: definition.ownerLane,
    projectionRefs: [projection],
    purpose: definition.purpose.name,
    purposeCode: 350,
    schemaDigest,
    schemaId: 24013,
    schemaVersion: '1.0.0',
    signatureContextRule:
      'PC_COSE_SIGN1_PROFILE_2_ES256_EXACT_TAGGED_PAYLOAD_DEFINITION_AAD_AND_ADMITTED_EVIDENCE_EXPORT_KEY',
    signed: true,
    typeName: definition.typeName,
  };
  for (const item of registry.entries)
    if (
      item.schemaId === entry.schemaId ||
      item.purpose === entry.purpose ||
      item.purposeCode === entry.purposeCode ||
      item.typeName === entry.typeName
    )
      if (JSON.stringify(item) !== JSON.stringify(entry))
        throw new Error('Evidence export allocation collision or frozen definition drift');
  if (!registry.entries.some((item) => item.schemaId === entry.schemaId))
    registry.entries.push(entry);
  const path = new URL('../src/evidence-export/generated.ts', import.meta.url);
  const context = {
    schemaId: entry.schemaId,
    schemaVersion: 1,
    purposeCode: entry.purposeCode,
    definitionDigest: schemaDigest,
    contentType: definition.cose.contentType,
    externalAadHex: definition.cose.externalAadHex,
    signatureProfileVersion: definition.cose.signatureProfileVersion,
    fields: definition.fields,
  };
  await emit(
    path,
    await format(
      `// Generated by the canonical receipt/profile generator. Do not edit.\nexport const evidenceExportCoseContext = ${JSON.stringify(context, null, 2)} as const;\n`,
      { ...(await resolveConfig(fileURLToPath(path))), parser: 'typescript' },
    ),
  );
}
