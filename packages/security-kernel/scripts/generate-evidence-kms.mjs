import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { definitionDigest } from '../src/business-transition/definition.ts';
import {
  evidenceKmsAllocations,
  assertEvidenceKmsAllocations,
} from '../src/evidence-kms/allocation.ts';

/** Called only by the canonical generator dispatch. No private registry or
 * fallback allocation, and no placeholder admission when a definition is absent. */
export async function registerEvidenceKmsProfiles(registry, root, emit) {
  assertEvidenceKmsAllocations(registry.entries);
  const profiles = {};
  for (const allocation of evidenceKmsAllocations) {
    const definition = JSON.parse(await readFile(new URL(allocation.projectionRef, root), 'utf8'));
    if (
      definition.schemaId !== allocation.schemaId ||
      definition.schemaVersion !== allocation.schemaVersion ||
      definition.semanticVersion !== allocation.semanticVersion ||
      definition.ownerLane !== allocation.ownerLane ||
      definition.typeName !== allocation.typeName ||
      definition.purpose?.name !== allocation.purpose ||
      definition.purpose?.code !== allocation.purposeCode ||
      definition.cose?.algorithm !== 'ES256' ||
      definition.cose?.signatureProfileVersion !== 2 ||
      definition.cose?.contentType !== 'application/pc+cbor' ||
      definition.cose?.externalAadHex !== '7063706c616e653a636f73652d7369676e313a763200' ||
      !Array.isArray(definition.fields) ||
      definition.fields.length < 2 ||
      definition.fields.some(
        (field, index) =>
          field.key !== index || typeof field.name !== 'string' || typeof field.type !== 'string',
      ) ||
      new Set(definition.fields.map((field) => field.name)).size !== definition.fields.length ||
      definition.fields[0].name !== 'schemaDefinitionDigest' ||
      definition.fields[0].type !== 'H32'
    )
      throw new Error('Evidence KMS definition/allocation mismatch');
    const schemaDigest = `sha256:${definitionDigest(definition).toString('hex')}`;
    const entry = {
      ownerLane: allocation.ownerLane,
      projectionRefs: [allocation.projectionRef],
      purpose: allocation.purpose,
      purposeCode: allocation.purposeCode,
      schemaDigest,
      schemaId: allocation.schemaId,
      schemaVersion: allocation.semanticVersion,
      signatureContextRule:
        'PC_COSE_SIGN1_PROFILE_2_ES256_EXACT_TAGGED_PAYLOAD_DEFINITION_AAD_AND_ADMITTED_EVIDENCE_KMS_ROLE',
      signed: true,
      typeName: allocation.typeName,
    };
    const existing = registry.entries.find((item) => item.schemaId === allocation.schemaId);
    if (existing) {
      const keys = Object.keys(entry).sort();
      if (
        Object.keys(existing).sort().join(',') !== keys.join(',') ||
        keys.some((key) => JSON.stringify(existing[key]) !== JSON.stringify(entry[key]))
      )
        throw new Error('Evidence KMS frozen definition drift');
    } else registry.entries.push(entry);
    profiles[allocation.typeName] = {
      schemaId: allocation.schemaId,
      schemaVersion: allocation.schemaVersion,
      purposeCode: allocation.purposeCode,
      definitionDigest: schemaDigest,
      contentType: definition.cose.contentType,
      externalAadHex: definition.cose.externalAadHex,
      signatureProfileVersion: definition.cose.signatureProfileVersion,
      fields: definition.fields,
    };
  }
  assertEvidenceKmsAllocations(registry.entries);
  const path = new URL('../src/evidence-kms/generated.ts', import.meta.url);
  await emit(
    path,
    await format(
      `// Generated by the canonical receipt/profile generator. Do not edit.\nexport const evidenceKmsCoseProfiles = ${JSON.stringify(profiles, null, 2)} as const;\n`,
      { ...(await resolveConfig(fileURLToPath(path))), parser: 'typescript' },
    ),
  );
}
