import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { definitionDigest } from '../src/business-transition/definition.ts';

export async function registerNotificationProfiles(registry, root, emit) {
  const contexts = {};
  for (const [file, schemaId, purposeCode, typeName] of [
    [
      'notification-completion-disposition-receipt-v1',
      24031,
      368,
      'NotificationCompletionDispositionReceiptV1',
    ],
    [
      'notification-completion-worker-profile-v1',
      24030,
      367,
      'NotificationCompletionWorkerProfileV1',
    ],
    [
      'notification-delivery-outcome-receipt-v1',
      24029,
      366,
      'NotificationDeliveryOutcomeReceiptV1',
    ],
    [
      'notification-delivery-cancellation-receipt-v1',
      24028,
      365,
      'NotificationDeliveryCancellationReceiptV1',
    ],
    ['notification-channel-profile-v1', 24009, 346, 'NotificationChannelProfileV1'],
    ['notification-delivery-receipt-v1', 24010, 347, 'NotificationDeliveryReceiptV1'],
    ['notification-verification-profile-v1', 24011, 348, 'NotificationVerificationProfileV1'],
    ['notification-verification-receipt-v1', 24012, 349, 'NotificationVerificationReceiptV1'],
    ['notification-routing-profile-v1', 24014, 351, 'NotificationRoutingProfileV1'],
    ['notification-worker-profile-v1', 24018, 355, 'NotificationWorkerProfileV1'],
    ['notification-occurrence-receipt-v1', 24019, 356, 'NotificationOccurrenceReceiptV1'],
    [
      'notification-delivery-started-receipt-v1',
      24021,
      358,
      'NotificationDeliveryStartedReceiptV1',
    ],
    [
      'notification-delivery-requested-receipt-v1',
      24020,
      357,
      'NotificationDeliveryRequestedReceiptV1',
    ],
  ]) {
    const projection = `schemas/canonical/${file}.json`;
    const definition = JSON.parse(await readFile(new URL(projection, root), 'utf8'));
    if (
      definition.schemaId !== schemaId ||
      definition.purpose.code !== purposeCode ||
      definition.schemaVersion !== 1 ||
      definition.semanticVersion !== '1.0.0' ||
      definition.typeName !== typeName ||
      definition.ownerLane !== 'LANE-CONTROL'
    )
      throw new Error('Notification schema allocation mismatch');
    const schemaDigest = `sha256:${definitionDigest(definition).toString('hex')}`;
    const entry = {
      ownerLane: definition.ownerLane,
      projectionRefs: [projection],
      purpose: definition.purpose.name,
      purposeCode,
      schemaDigest,
      schemaId,
      schemaVersion: '1.0.0',
      signatureContextRule:
        'PC_COSE_SIGN1_PROFILE_2_ES256_EXACT_TAGGED_PAYLOAD_DEFINITION_AAD_AND_INSTALLED_NOTIFICATION_KEY',
      signed: true,
      typeName,
    };
    for (const item of registry.entries) {
      if (
        item.schemaId === schemaId ||
        item.purpose === entry.purpose ||
        item.purposeCode === purposeCode ||
        item.typeName === typeName
      ) {
        if (JSON.stringify(item) !== JSON.stringify(entry))
          throw new Error('Notification allocation collision or frozen definition drift');
      }
    }
    if (!registry.entries.some((item) => item.schemaId === schemaId)) registry.entries.push(entry);
    contexts[typeName] = {
      schemaId,
      schemaVersion: 1,
      purposeCode,
      definitionDigest: schemaDigest,
      contentType: definition.cose.contentType,
      externalAadHex: definition.cose.externalAadHex,
      signatureProfileVersion: definition.cose.signatureProfileVersion,
      fields: definition.fields,
    };
  }
  const path = new URL('../src/notification-gateway/generated.ts', import.meta.url);
  await emit(
    path,
    await format(
      `// Generated by the canonical receipt/profile generator. Do not edit.\nexport const notificationCoseProfiles = ${JSON.stringify(contexts, null, 2)} as const;\n`,
      { ...(await resolveConfig(fileURLToPath(path))), parser: 'typescript' },
    ),
  );
}
