import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { definitionDigest } from '../src/business-transition/definition.ts';

export async function registerOperationsConfigurationProfiles(registry, root, emit) {
  const contexts = {};
  for (const [file, schemaId, purposeCode, typeName, issuerContext] of [
    [
      'operations-site-document-v1',
      24022,
      359,
      'OperationsSiteDocumentV1',
      'INSTALLED_OPERATIONS_SITE_ISSUER',
    ],
    [
      'operations-secret-resolution-v1',
      24023,
      360,
      'OperationsSecretResolutionV1',
      'INSTALLED_TEST_SECRET_RESOLUTION_OBSERVER',
    ],
    [
      'operations-qualification-input-v1',
      24024,
      361,
      'OperationsQualificationInputV1',
      'INSTALLED_QUALIFICATION_PURPOSE_KEY_AND_FRESH_ROOT_STATE',
    ],
    [
      'operations-qualification-executed-receipt-v1',
      24025,
      362,
      'OperationsQualificationExecutedReceiptV1',
      'INSTALLED_QUALIFICATION_PURPOSE_KEY_AND_FRESH_ROOT_STATE',
    ],
    [
      'operations-qualification-keyset-v1',
      24026,
      363,
      'OperationsQualificationKeysetV1',
      'INSTALLED_QUALIFICATION_ROOT_AND_MONOTONIC_STATE',
    ],
    [
      'operations-qualification-revocations-v1',
      24027,
      364,
      'OperationsQualificationRevocationsV1',
      'INSTALLED_QUALIFICATION_ROOT_AND_MONOTONIC_STATE',
    ],
    [
      'operations-notification-async-input-v1',
      24032,
      369,
      'OperationsNotificationAsyncInputV1',
      'INSTALLED_ASYNC_QUALIFICATION_PURPOSE_KEY_AND_CURRENT_NATIVE_SOURCE_OWNER',
    ],
    [
      'operations-notification-async-capacity-receipt-v1',
      24033,
      370,
      'OperationsNotificationAsyncCapacityReceiptV1',
      'INSTALLED_ASYNC_QUALIFICATION_PURPOSE_KEY_AND_CURRENT_NATIVE_EXECUTION_REVIEW_OWNER',
    ],
  ]) {
    const projection = `schemas/canonical/${file}.json`;
    const definition = JSON.parse(await readFile(new URL(projection, root), 'utf8'));
    if (
      definition.schemaId !== schemaId ||
      definition.purpose.code !== purposeCode ||
      definition.schemaVersion !== 1 ||
      definition.semanticVersion !== '1.0.0' ||
      definition.typeName !== typeName ||
      definition.ownerLane !== 'LANE-CONTROL'
    )
      throw new Error('Operations configuration schema allocation mismatch');
    const schemaDigest = `sha256:${definitionDigest(definition).toString('hex')}`;
    const entry = {
      ownerLane: definition.ownerLane,
      projectionRefs: [projection],
      purpose: definition.purpose.name,
      purposeCode,
      schemaDigest,
      schemaId,
      schemaVersion: '1.0.0',
      signatureContextRule: `PC_COSE_SIGN1_PROFILE_2_ES256_EXACT_TAGGED_PAYLOAD_DEFINITION_AAD_AND_${issuerContext}`,
      signed: true,
      typeName,
    };
    for (const item of registry.entries) {
      if (
        item.schemaId === schemaId ||
        item.purpose === entry.purpose ||
        item.purposeCode === purposeCode ||
        item.typeName === typeName
      ) {
        if (JSON.stringify(item) !== JSON.stringify(entry))
          throw new Error(
            'Operations configuration allocation collision or frozen definition drift',
          );
      }
    }
    if (!registry.entries.some((item) => item.schemaId === schemaId)) registry.entries.push(entry);
    contexts[typeName] = {
      schemaId,
      schemaVersion: 1,
      purposeCode,
      definitionDigest: schemaDigest,
      contentType: definition.cose.contentType,
      externalAadHex: definition.cose.externalAadHex,
      signatureProfileVersion: definition.cose.signatureProfileVersion,
      fields: definition.fields,
    };
  }
  const path = new URL('../src/operations-configuration/generated.ts', import.meta.url);
  await emit(
    path,
    await format(
      `// Generated by the canonical receipt/profile generator. Do not edit.\nexport const operationsConfigurationCoseProfiles = ${JSON.stringify(contexts, null, 2)} as const;\n`,
      { ...(await resolveConfig(fileURLToPath(path))), parser: 'typescript' },
    ),
  );
}
