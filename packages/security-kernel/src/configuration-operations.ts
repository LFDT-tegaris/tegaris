export type ConfigurationMutationOperation = (typeof configurationMutationOperations)[number];
export type ConfigurationMutationOperationId = ConfigurationMutationOperation['catalogOperationId'];

export function configurationMutationOperation(
  id: ConfigurationMutationOperationId,
): ConfigurationMutationOperation {
  const operation = configurationMutationOperations.find(
    (entry) => entry.catalogOperationId === id,
  );
  if (operation === undefined) throw new Error('Unknown configuration mutation operation');
  return operation;
}

export function configurationMutationForAction(
  actionIntentId: string,
): ConfigurationMutationOperation | undefined {
  return configurationMutationOperations.find((entry) => entry.actionIntentId === actionIntentId);
}
