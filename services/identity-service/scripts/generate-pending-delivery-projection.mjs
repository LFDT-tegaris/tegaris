const immutableBytes32 = z.unknown().transform((value, context) => {
  const reject = () => {
    context.addIssue({ code: 'custom', message: 'value must contain exactly 32 owned bytes' });
    return z.NEVER;
  };
  if (utilityTypes.isProxy(value)) return reject();
  if (!Buffer.isBuffer(value) || Object.getPrototypeOf(value) !== Buffer.prototype) {
    return reject();
  }
  const expectedKeys = Array.from({ length: 32 }, (_, index) => String(index));
  const keys = Reflect.ownKeys(value);
  if (keys.length !== expectedKeys.length || keys.some((key, index) => key !== expectedKeys[index])) {
    return reject();
  }
  const bytes: number[] = [];
  for (const key of expectedKeys) {
    const descriptor = Object.getOwnPropertyDescriptor(value, key);
    if (
      descriptor === undefined ||
      !('value' in descriptor) ||
      !descriptor.enumerable ||
      !Number.isInteger(descriptor.value) ||
      descriptor.value < 0 ||
      descriptor.value > 255
    ) {
      return reject();
    }
    bytes.push(descriptor.value);
  }
  const copy = Buffer.allocUnsafe(32);
  bytes.forEach((byte, index) => {
    copy[index] = byte;
  });
  return copy;
});

